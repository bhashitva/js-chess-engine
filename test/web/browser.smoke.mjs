// End-to-end project test for CI or a developer's isolated Playwright browser.
import { chromium } from 'playwright';
import { strict as assert } from 'node:assert';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createStaticServer } from '../../web/serve.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const server = createStaticServer(path.join(root, 'web/dist'));
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const url = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 1100 } });
page.setDefaultTimeout(90000);
const failures = [], external = [];
page.on('pageerror', error => failures.push(error.message));
page.on('request', request => { if (!request.url().startsWith(url)) external.push(request.url()); });
const square = value => page.locator(`[data-square="${value}"]`);
const idle = () => page.locator('#board[aria-busy=false]').waitFor();
async function load(fen) {
  await page.getByRole('button', { name: /Position \/ FEN/u }).click();
  await page.getByLabel('FEN position').fill(fen);
  await page.getByRole('button', { name: 'Load position', exact: true }).click();
  await page.locator('#position-dialog').waitFor({ state: 'hidden' }); await idle();
}
try {
  await page.goto(url); await idle();
  await page.getByLabel('PLAY AGAINST', { exact: true }).selectOption('local');
  await square('E2').click(); assert.match(await square('E4').getAttribute('class'), /legal/u);
  await square('E4').click(); await idle();
  assert.match(await square('E4').getAttribute('aria-label'), /white pawn/u);
  assert.equal(await page.locator('#turn-label').innerText(), 'Black to move');
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await idle();
  assert.match(await square('E2').getAttribute('aria-label'), /white pawn/u);
  await page.getByRole('button', { name: 'Flip board', exact: true }).click();
  assert.equal(await page.locator('#board button').first().getAttribute('data-square'), 'H1');
  await page.getByRole('button', { name: 'Flip board', exact: true }).click();
  await load('4k3/P7/8/8/8/8/8/4K3 w - - 0 1');
  await square('A7').click(); await square('A8').click();
  await page.getByRole('button', { name: 'Promote to knight', exact: true }).click(); await idle();
  assert.match(await square('A8').getAttribute('aria-label'), /white knight/u);
  await page.reload(); await idle(); assert.match(await square('A8').getAttribute('aria-label'), /white knight/u);
  await page.getByRole('button', { name: /Position \/ FEN/u }).click();
  await page.getByLabel('FEN position').fill('invalid FEN');
  await page.getByRole('button', { name: 'Load position', exact: true }).click();
  await page.getByText('That position could not be loaded. Check all six FEN fields.').waitFor();
  await page.getByRole('button', { name: 'Back to the game', exact: true }).click();
  assert.match(await square('A8').getAttribute('aria-label'), /white knight/u);
  await load('7k/6Q1/6K1/8/8/8/8/8 b - - 0 1');
  assert.equal(await page.locator('#turn-label').innerText(), 'White wins');
  await page.getByRole('button', { name: /New game/u }).click(); await idle();
  await page.getByLabel('PLAY AGAINST', { exact: true }).selectOption('ai');
  await square('E2').click(); await square('E4').click();
  await page.getByText('2 moves', { exact: true }).waitFor(); await idle();
  assert.equal(await page.locator('#turn-label').innerText(), 'White to move');
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await idle();
  assert.equal(await page.locator('#move-count').innerText(), '0 moves');
  await page.locator('[data-level="5"]').click();
  await page.getByRole('button', { name: 'Ask Bhash to play this turn', exact: true }).click();
  await page.getByRole('button', { name: 'Stop thinking', exact: true }).click(); await idle();
  assert.equal(await page.locator('#move-count').innerText(), '0 moves');
  await page.locator('[data-level="1"]').click();
  await mkdir(path.join(root, '.bhash-build'), { recursive: true });
  await page.screenshot({ path: path.join(root, '.bhash-build/web-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: path.join(root, '.bhash-build/web-mobile.png'), fullPage: true });
  assert.deepEqual(failures, []); assert.deepEqual(external, []);
  console.log('Browser checks passed: real WASM moves/AI, undo, orientation, promotion, FEN errors, reload, mate, cancellation, mobile layout; no external requests.');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
